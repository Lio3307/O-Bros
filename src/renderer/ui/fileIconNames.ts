const DEFAULT_FILE = 'file'
const DEFAULT_FOLDER = 'folder'
const DEFAULT_OPEN_FOLDER = 'folder-open'

function extensionCandidates(fileName: string): string[] {
  const parts = fileName.split('.')
  return parts.slice(1).map((_part, index) => parts.slice(index + 1).join('.'))
}

export function fileIconName(fileName: string, hasIcon: (name: string) => boolean): string {
  const lower = fileName.toLowerCase()
  const byName = FILE_NAMES[lower] ?? FILE_NAME_PREFIXES.find(([prefix]) => lower.startsWith(prefix))?.[1]
  if (byName !== undefined && hasIcon(byName)) {
    return byName
  }
  for (const extension of extensionCandidates(lower)) {
    const name = EXTENSIONS[extension] ?? extension
    if (hasIcon(name)) {
      return name
    }
  }
  return DEFAULT_FILE
}

export function folderIconName(folderName: string, isOpen: boolean, hasIcon: (name: string) => boolean): string {
  const lower = folderName.toLowerCase()
  const named = FOLDER_NAMES[lower] ?? `folder-${lower}`
  if (hasIcon(named)) {
    const openName = `${named}-open`
    return isOpen && hasIcon(openName) ? openName : named
  }
  return isOpen ? DEFAULT_OPEN_FOLDER : DEFAULT_FOLDER
}

export function mappedIconNames(): string[] {
  return [...Object.values(FILE_NAMES), ...FILE_NAME_PREFIXES.map(([, name]) => name), ...Object.values(EXTENSIONS), ...Object.values(FOLDER_NAMES)]
}
